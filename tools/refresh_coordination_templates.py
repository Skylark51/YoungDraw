"""Refresh bundled motifs from checked-in scaffolds, without RDKit/source drives."""
from pathlib import Path
import copy
import hashlib
import json
import xml.etree.ElementTree as ET
from coordination_motifs import add_motif, validate_motif
from template_presentation import apply_presentation

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'resources' / 'lab_templates'
LABELS = {'nitrosyl': '{MNO}6 · nitrosyl (N-bound)', 'nitro': 'nitrite · nitro (N-bound)',
          'nitrito': 'nitrite · nitrito (O-bound)', 'nitrite-bidentate': 'nitrite · bidentate (O,O)'}


def refresh():
    entries = json.loads((OUT / 'manifest.json').read_text(encoding='utf-8'))
    entries = [e for e in entries if e.get('motif') not in LABELS]

    def store(entry, root):
        data = ET.tostring(root, encoding='unicode')
        (OUT / (entry['slug'] + '.ydraw')).write_text(data, encoding='utf-8')
        entry.update(atoms=len(root.findall('atom')), bonds=len(root.findall('bond')),
                     sha256=hashlib.sha256(data.encode()).hexdigest())

    for entry in entries:
        slug = entry['slug']
        if not any(slug.endswith('-' + name) for name in ['peroxo-side', 'peroxo-end', 'hydroperoxo-side', 'hydroperoxo-end']):
            continue
        species = next(name for name in ['hydroperoxo-side', 'hydroperoxo-end', 'peroxo-side', 'peroxo-end'] if slug.endswith('-' + name))
        orientation = 'axial' if '-axial-' in slug else 'equatorial'
        root = ET.parse(OUT / (slug + '.ydraw')).getroot()
        # These seven donor scaffolds have no oxygen of their own.
        removed = {a.get('id') for a in root.findall('atom') if a.get('e') in ['8', '1']}
        for child in list(root):
            if child.get('id') in removed or (child.tag == 'bond' and (child.get('a') in removed or child.get('b') in removed)):
                root.remove(child)
        metal = int(next(a for a in root.findall('atom') if a.get('label') == 'M').get('id'))
        add_motif(root, metal, species, orientation)
        validate_motif(root, metal, species)
        entry['geometryRevision'] = 2
        store(entry, root)

    bases = [e for e in entries if e['slug'].endswith(('-axial-open', '-equatorial-open'))]
    for base in bases:
        orientation = 'axial' if '-axial-' in base['slug'] else 'equatorial'
        ligand = base['slug'].rsplit('-' + orientation + '-open', 1)[0]
        for species, label in LABELS.items():
            scaffold = OUT / (base['slug'] + '.ydraw')
            if ligand == 'mpdap' and species == 'nitrite-bidentate':
                scaffold = OUT / f'mpdap-{orientation}-peroxo-side.ydraw'
            root = ET.parse(scaffold).getroot()
            removed = {a.get('id') for a in root.findall('atom') if a.get('e') in ['8', '1']}
            for child in list(root):
                if child.get('id') in removed or (child.tag == 'bond' and (child.get('a') in removed or child.get('b') in removed)):
                    root.remove(child)
            atom = next(a for a in root.findall('atom') if a.get('label') == 'M')
            atom.set('e', '26')
            metal = int(atom.get('id'))
            add_motif(root, metal, species, orientation)
            validate_motif(root, metal, species)
            ligand_name = base['name'].split(' · ')[0]
            entry = dict(slug=f'{ligand}-{orientation}-{species}', category=base['category'],
                         name=f'{ligand_name} · {label}' + (' (kappa4)' if ligand == 'mpdap' and species == 'nitrite-bidentate' else ''),
                         source=base['source'] + '; editable generic M-NOx schematic',
                         projection=orientation, motif=species, schematic=True, geometryRevision=2)
            if species == 'nitrosyl':
                entry['notation'] = '{MNO}6 drawing reference; metal oxidation state and spin are unspecified'
            store(entry, root)
            entries.append(entry)

    for entry in entries:
        root = ET.parse(OUT / (entry['slug'] + '.ydraw')).getroot()
        apply_presentation(root, entry['slug'])
        store(entry, root)
    (OUT / 'manifest.json').write_text(json.dumps(entries, ensure_ascii=False, indent=2), encoding='utf-8')
    header = ['// Generated by tools/prepare_lab_templates.py + tools/refresh_coordination_templates.py.',
              '#pragma once', 'namespace yd {',
              'struct LabTemplate {const char* category;const char* name;const char* data;const char* source;};',
              'inline const LabTemplate labTemplates[] = {']
    for entry in entries:
        data = (OUT / (entry['slug'] + '.ydraw')).read_text(encoding='utf-8')
        q = lambda value: json.dumps(value, ensure_ascii=False)
        header.append('{' + q(entry['category']) + ',' + q(entry['name']) + ',R"YDRAW(' + data + ')YDRAW",' + q(entry['source']) + '},')
    (ROOT / 'src' / 'lab_templates_data.h').write_text('\n'.join(header + ['};', '}']), encoding='utf-8')
    print(f'Refreshed {len(entries)} editable templates; added {len(bases) * len(LABELS)} M-NOx variants.')


if __name__ == '__main__':
    refresh()
